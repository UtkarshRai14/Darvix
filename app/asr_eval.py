"""Language-specific ASR evaluation for the Philippines and Indonesia bots.

    python -m app.asr_eval            ->  reports/asr_report.md + reports/asr_report.json

For every utterance in data/asr_eval/utterances.json and every voice of that market:
  - audio: a human recording at data/asr_eval/human/<profile>/<voice_key>/<id>.wav if present,
           otherwise synthesised with the market's neural voice (cached in data/asr_eval/audio/)
  - ASR is run twice: the market config (language + domain prompt from the profile) and a baseline
    (auto language detection, no prompt), so the effect of the configuration is measured.
Metrics: WER, finance-term recall (were key terms transcribed, and not translated?), detected language.
Indonesian accent coverage uses Javanese (jv-ID) and Sundanese (su-ID) voices reading the same Indonesian
sentences: a synthetic proxy for regional accents, not a substitute for recordings of real speakers.
"""
from __future__ import annotations

import asyncio
import json
from collections import defaultdict

import numpy as np

from app.agent.rules import load_profiles
from app.audio import mp3_to_pcm16k, wav_bytes
from app.config import ASR_MODEL, DATA_DIR, REPORTS_DIR
from app.llm import atranscribe
from app.metrics import normalize_words, wer
from app.tts import synthesize

BASE = DATA_DIR / "asr_eval"


async def _audio(profile_id: str, voice_key: str, voice: str, utt: dict) -> tuple[bytes, str]:
    human = BASE / "human" / profile_id / voice_key / f"{utt['id']}.wav"
    if human.exists():
        return human.read_bytes(), "human recording"
    cached = BASE / "audio" / profile_id / voice_key / f"{utt['id']}.wav"
    if not cached.exists():
        cached.parent.mkdir(parents=True, exist_ok=True)
        mp3, _ = await synthesize(utt["text"], voice)
        cached.write_bytes(wav_bytes(mp3_to_pcm16k(mp3)))
    return cached.read_bytes(), f"synthetic ({voice})"


def _term_recall(reference: str, hypothesis: str, terms: list[str]) -> tuple[int, int, list[str]]:
    ref, hyp = " ".join(normalize_words(reference)), " ".join(normalize_words(hypothesis))
    present = [t for t in terms if " ".join(normalize_words(t)) in ref]
    missed = [t for t in present if " ".join(normalize_words(t)) not in hyp]
    return len(present) - len(missed), len(present), missed


async def evaluate() -> dict:
    spec = json.loads((BASE / "utterances.json").read_text(encoding="utf-8"))
    profiles = load_profiles()
    results = {}
    for profile_id, market in spec.items():
        cfg = profiles[profile_id]["asr"]
        rows = []
        for voice_key, voice in market["voices"].items():
            for utt in market["utterances"]:
                wav, source = await _audio(profile_id, voice_key, voice, utt)
                for mode, lang, prompt in (("configured", cfg["language"], cfg["prompt"]), ("baseline", None, None)):
                    asr = await atranscribe(wav, language=lang, prompt=prompt)
                    score, errors = wer(utt["text"], asr["text"])
                    hit, total, missed = _term_recall(utt["text"], asr["text"], market["key_terms"])
                    rows.append({"id": utt["id"], "voice": voice_key, "source": source, "mode": mode,
                                 "tags": utt["tags"], "reference": utt["text"], "hypothesis": asr["text"],
                                 "wer": round(score, 3), "errors": errors[:6], "terms_hit": hit, "terms_total": total,
                                 "terms_missed": missed, "detected_language": asr.get("language"),
                                 "latency_ms": asr["ms"], "avg_logprob": asr.get("avg_logprob")})
                    print(f"{profile_id} {voice_key:<24} {mode:<10} WER {score:.2f} | {asr['text']}")
        results[profile_id] = {"config": cfg, "rows": rows}
    return results


def _mean(rows, key="wer"):
    vals = [r[key] for r in rows]
    return round(float(np.mean(vals)), 3) if vals else None


def write_report(results: dict) -> None:
    lines = ["# Language-specific ASR evaluation", "",
             f"Provider/model: Groq `{ASR_MODEL}` (Whisper large-v3 turbo). Generated by `python -m app.asr_eval`.",
             "WER = word error rate (lower is better). Term recall = finance/local terms in the reference that "
             "were transcribed as spoken (not dropped or translated).", ""]
    for profile_id, data in results.items():
        rows, cfg = data["rows"], data["config"]
        lines += [f"## {profile_id}", "",
                  f"- Configured: `language={cfg['language']}`, domain prompt: \"{cfg['prompt']}\"",
                  "- Baseline: automatic language detection, no prompt", ""]
        lines += ["| Voice | Mode | Mean WER | Term recall | Mean latency (ms) |", "|---|---|---|---|---|"]
        groups = defaultdict(list)
        for r in rows:
            groups[(r["voice"], r["mode"])].append(r)
        for (voice, mode), g in groups.items():
            hit, tot = sum(r["terms_hit"] for r in g), sum(r["terms_total"] for r in g)
            lines.append(f"| {voice} | {mode} | {_mean(g)} | {hit}/{tot} | {_mean(g, 'latency_ms')} |")
        tag_groups = defaultdict(list)
        for r in rows:
            if r["mode"] == "configured":
                for t in r["tags"]:
                    tag_groups[t].append(r)
        lines += ["", "Mean WER by utterance type (configured mode, all voices): " +
                  ", ".join(f"{t} {_mean(g)}" for t, g in sorted(tag_groups.items())), ""]
        lines += ["| ID | Voice | Mode | Reference | Transcript | WER | Missed terms | Detected lang |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            lines.append(f"| {r['id']} | {r['voice']} | {r['mode']} | {r['reference']} | {r['hypothesis']} | "
                         f"{r['wer']} | {', '.join(r['terms_missed']) or '-'} | {r['detected_language'] or '-'} |")
        lines.append("")
    (REPORTS_DIR / "asr_report.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (REPORTS_DIR / "asr_report.json").write_text(json.dumps(results, indent=2, ensure_ascii=False), encoding="utf-8")
    print("wrote reports/asr_report.md")


if __name__ == "__main__":
    write_report(asyncio.run(evaluate()))
